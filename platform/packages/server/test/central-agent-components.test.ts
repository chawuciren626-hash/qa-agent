import {afterEach,beforeEach,expect,it} from "vitest";
import {DatabaseSync} from "node:sqlite";
import {ControlStore,publicPayload,controlRoutes} from "../src/http/control-plane.js";
import {Hono} from "hono";
import type {AppEnv} from "../src/auth/middleware.js";
import {agentComponents,agentComponentCounts} from "../src/http/central-agent-components.js";
let db:DatabaseSync,store:ControlStore;
beforeEach(()=>{db=new DatabaseSync(":memory:");db.exec("CREATE TABLE users(user_id TEXT PRIMARY KEY,is_admin INTEGER NOT NULL DEFAULT 0); INSERT INTO users VALUES ('admin',1);");store=new ControlStore(db);});
afterEach(()=>db.close());
it("shows migrated current dependencies but never fabricates old snapshots",async()=>{
 let skill=store.save("admin",{kind:"skills",name:"test-skill",description:"description",payload:{skillName:"test-skill",content:"---\nname: test-skill\ndescription: description\n---\n\n# Actual skill"},audience:["*"]});
 skill=store.publish("admin",skill.id,skill.revision);
 let agent=store.save("admin",{kind:"agents",name:"Agent",payload:{agentId:"test_agent",prompt:"p",agentsMd:"a",skillResources:[skill.id]},audience:["*"]});
 agent=store.publish("admin",agent.id,agent.revision);
 db.prepare("DELETE FROM public_resource_version_pins WHERE resource_id=?").run(agent.id);
 const current=await agentComponents(store,agent.id,"1");
 expect(current.skills[0]?.name).toBe("test-skill");
 expect(current.skills[0]?.files["SKILL.md"]).toContain("Actual skill");
 expect(current.warning).toBe("");
 expect(agentComponentCounts(store,agent.id,"1")).toEqual({skillCount:current.skills.length,hookCount:current.hooks.length});
 const copy=store.copyAgent("admin",agent.id,1,agent.revision);store.publish("admin",agent.id,copy.revision);
 const old=await agentComponents(store,agent.id,"1");
 expect(old.skills[0]?.name).toBe("test-skill");expect(old.skills[0]?.files).toEqual({});expect(old.skills[0]?.archiveBase64).toBe("");expect(old.warning).toContain("快照");
 expect(agentComponentCounts(store,agent.id,"1")).toEqual({skillCount:old.skills.length,hookCount:old.hooks.length});
 const draft=await agentComponents(store,agent.id,"draft");
 expect(agentComponentCounts(store,agent.id,"draft")).toEqual({skillCount:draft.skills.length,hookCount:draft.hooks.length});
});
it("persists skills injection and hook switches without accepting unknown fields",()=>{
 const value=publicPayload("agents",{prompt:"p",skills:{enabled:false,prompt:"{{SKILL_METADATA}}"},hooks:{enabled:false}});
 expect(value.skills).toEqual({enabled:false,prompt:"{{SKILL_METADATA}}"});expect(value.hooks).toEqual({enabled:false});
 expect(()=>publicPayload("agents",{prompt:"p",hooks:{enabled:"false"}})).toThrow();
 expect(()=>publicPayload("agents",{prompt:"p",skills:{directory:"/local"}})).toThrow();
});
it("edits the live Agent atomically and lists it once without losing old task snapshots",async()=>{
 let agent=store.save("admin",{kind:"agents",name:"Agent",payload:{agentId:"test_agent",prompt:"p",agentsMd:"a"},audience:["*"]});
 agent=store.publish("admin",agent.id,agent.revision);
 const body={kind:"agents",name:"Updated",payload:{...agent.payload,prompt:"changed"},audience:agent.audience,revision:agent.revision};
 const changed=store.saveLiveAgent("admin",agent.id,body);
 expect(store.get(agent.id).name).toBe("Updated");
 expect(store.getVersion(agent.id,1).payload.prompt).toBe("p");
 expect(changed.hasWorkCopy).toBe(false);
 expect(()=>store.saveLiveAgent("admin",agent.id,body)).toThrow();
 expect(()=>store.saveLiveAgent("admin",agent.id,{...body,revision:changed.revision,payload:{...body.payload,prompt:""}})).toThrow();
 expect(store.get(agent.id,true).revision).toBe(changed.revision);
 expect(store.get(agent.id,true).payload.prompt).toBe("changed");
 const app=new Hono<AppEnv>();app.use("*",async(c,next)=>{c.set("user",{userId:"admin",isAdmin:true} as AppEnv["Variables"]["user"]);await next();});app.route("/control",controlRoutes(store));
 const response=await app.request("/control/admin/agent-cards");
 expect(response.status).toBe(200);
 expect((await response.json()).cards).toHaveLength(1);
});
