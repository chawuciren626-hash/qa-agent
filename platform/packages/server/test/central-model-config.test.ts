import { DatabaseSync } from "node:sqlite";
import { mkdtempSync, readFileSync, rmSync, mkdirSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { Hono } from "hono";
import { expect, it } from "vitest";
import { CentralModelConfig, centralModelConfigRoutes, CENTRAL_MODEL_CATALOG_ID as id } from "../src/http/central-model-config.js";
import type { AppEnv } from "../src/auth/middleware.js";

it("migrates the complete catalogue, masks credentials, preserves keys on edits, persists across restart and rejects duplicate import", async () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "central-models-"));
  const db = new DatabaseSync(path.join(root, "web.db"));
  try {
    const service = new CentralModelConfig(db, root);
    const source = { models: { providers: { custom: { api_key: "provider-secret-test", base_url: "https://example.com/v1", client_type: "openai-chat" } }, models: [{ provider: "custom", model_id: "example", display_name: "Example", api_key: "model-secret-test", context_window: 32000 }], default_model: { provider: "custom", model_id: "example" } }, promotions: [{ provider: "custom", modelId: "example", discount: 0.5 }] };
    const result = await service.importAccount(source);
    expect(result.models).toHaveLength(1);
    expect(result.models[0]?.discount).toBe(0.5);
    mkdirSync(path.join(root, "admin_agent_catalog"));
    const runtimeFile = path.join(root, "admin_agent_catalog", ".project_config.toml");
    writeFileSync(runtimeFile, 'name = "Assistant"\n');
    await service.syncAssistantRuntime(root);
    expect(readFileSync(runtimeFile, "utf8")).toContain('name = "Assistant"');
    expect(readFileSync(runtimeFile, "utf8")).toContain("model-secret-test");
    expect(JSON.stringify(result)).not.toContain("model-secret-test");
    expect(readFileSync(path.join(root, "web.db")).toString()).not.toContain("provider-secret-test");
    await service.setProviderConnection(id, "custom", { baseUrl: "https://example.org/v1" });
    await service.updateModels(id, { models: [{ provider: "custom", modelId: "example", displayName: "Changed", contextWindow: 64000 }], defaultModel: { provider: "custom", modelId: "example" } });
    const reopened = new CentralModelConfig(db, root);
    const raw = await reopened.readRaw(id);
    expect((raw.providers as any).custom.api_key).toBe("provider-secret-test");
    expect((raw.models as any[])[0].api_key).toBe("model-secret-test");
    expect((await reopened.getModels(id)).models[0]?.displayName).toBe("Changed");
    await expect(reopened.importAccount(source)).rejects.toThrow("已迁移");
    const app = new Hono<AppEnv>();
    app.use("*", async (c, next) => { c.set("user", { userId: "test", isAdmin: c.req.header("x-test-admin") === "yes" } as any); await next(); });
    app.route("/config", centralModelConfigRoutes(reopened));
    app.onError((e, c) => c.json({ error: e.message }, (e as any).status ?? 500));
    expect((await app.request(`/config/${id}`)).status).toBe(403);
    const response = await app.request(`/config/${id}`, { headers: { "x-test-admin": "yes" } });
    expect(response.status).toBe(200);
    expect((await response.json() as {models:{displayName:string}[]}).models[0]!.displayName).toBe("Changed");
    const edited = await app.request(`/config/${id}`, { method: "PUT", headers: { "x-test-admin": "yes", "content-type": "application/json" }, body: JSON.stringify({ models: [{ provider: "custom", modelId: "example", displayName: "Route edit" }] }) });
    expect(edited.status, await edited.clone().text()).toBe(200);
    const renamed=await app.request(`/config/${id}/providers/custom`,{method:"PUT",headers:{"x-test-admin":"yes","content-type":"application/json"},body:JSON.stringify({displayName:"测试渠道"})});
    expect(renamed.status).toBe(200);
    expect((await renamed.json() as {providers:{custom:{displayName:string}}}).providers.custom.displayName).toBe("测试渠道");
    const afterRename=await reopened.readRaw(id);
    expect((afterRename.providers as any).custom.api_key).toBe("provider-secret-test");
    expect((afterRename.providers as any).custom.base_url).toBe("https://example.org/v1");
    expect((afterRename.models as any[])[0].provider).toBe("custom");
    const forbiddenDelete = await app.request(`/config/${id}/providers/custom`, {method:"DELETE"});
    expect(forbiddenDelete.status).toBe(403);
    const deleted = await app.request(`/config/${id}/providers/custom`, {method:"DELETE",headers:{"x-test-admin":"yes"}});
    expect(deleted.status).toBe(200);
    const remaining = await reopened.readRaw(id);
    expect(remaining.models).toEqual([]);
    expect((remaining.providers as any).custom).toBeUndefined();
    expect(remaining.default_model).toBeUndefined();
    expect((await reopened.getModels(id)).models).toEqual([]);
    await reopened.syncAssistantRuntime(root);
    expect(readFileSync(runtimeFile,"utf8")).not.toContain("model-secret-test");
    expect(readFileSync(runtimeFile,"utf8")).not.toContain("provider-secret-test");
  } finally { db.close(); rmSync(root, { recursive: true, force: true }); }
});
